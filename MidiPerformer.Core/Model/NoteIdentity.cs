namespace MidiPerformer.Core.Model;

/// <summary>
/// **发身份的地方** —— 整条链上只有这里写出新的 <see cref="NoteId"/>。
///
/// 为什么身份是**发的**，不是**算的**（比如拿音高 + 起点拼一个）：算出来的东西碰上两个一模一样的音
/// 就分不开。同一个 tick 上同音高同力度的两个音在真实语料里常见（两条声部撞在一起、一个音被复制过），
/// 它们会拿到同一个身份，于是「选中了哪一个」这句话又变得没有意义。发号不会撞：发过的号不再发。
///
/// 为什么发号必须**可重现**：全链对拍那几条测试拿「同样的输入读两遍，两份 <see cref="Song"/>
/// 逐字段相等」当尺子。发号只要带上一点随机、或者依赖一个跨文件累加的全局计数器，
/// 对拍会红 —— 而且红得像是读取逻辑坏了，查半天查到发号上。所以这里发出的号
/// **只由这一次读取的音符顺序决定**：一轨一轨地从头数，第几个音就是几号。
///
/// 为什么不用「整份曲子一个计数器」：跨轨发号会让轨的顺序影响号
/// （按声道拆轨的先后、将来某个改动的先后），而身份只需要在**一条轨内**唯一 ——
/// 指着某个音的地方本来就带着轨那一半（见 <see cref="NoteRef"/>）。一轨一数，少一层依赖。
///
/// 两条入口都用这里的号：MIDI 导入（<c>MidiReader</c>）和读工程文件（<c>SongProjectFile</c>）。
/// 同一份谱面从哪条路进来，发出的号必须一模一样，否则「存盘再打开」和「重新导入同一个 MIDI」
/// 会给出两套身份，而没有任何东西会提醒你。
/// </summary>
internal static class NoteIdentity
{
    /// <summary>
    /// 给一轨音符按**给定顺序**发号：1、2、3……（<paramref name="notes"/> 的顺序就是号的顺序）。
    ///
    /// 顺序由调用方负责：导入端给的是「按起始 tick 排好的那一份」，读工程文件端给的是文件里的顺序。
    /// 这里再排一次是错的 —— 排序是 <see cref="Track.WithNotes"/> 的活儿，
    /// 而且同一起点的音排序前后会换位置，号就跟着换，等于发号依赖了一个不该由它管的东西。
    /// </summary>
    internal static Note[] AssignInOrder(IReadOnlyList<Note> notes)
    {
        var numbered = new Note[notes.Count];
        for (int i = 0; i < notes.Count; i++)
            numbered[i] = notes[i] with { Id = new NoteId(i + 1) };
        return numbered;
    }

    /// <summary>
    /// 这一轨**下一个能用的号**：现有身份的最大值 + 1（一个音都没有时是 1）。剪切用来给新音发号。
    ///
    /// 为什么从最大值往上发，而不是「数一数这条轨有几个音」：按数量发会**重号**。
    /// 剪一刀发掉一个号，之后删掉一个音再剪一刀，按数量算就会把刚删掉的那个号又发一次，
    /// 而那个号可能还留在别处（撤销栈里的旧曲子、界面手里的旧坐标）。
    /// 往上发至少保证「同一份曲子里正在用的号不会重复」。
    ///
    /// 代价说清楚：往上发也不是绝对不会重号 —— 删掉号最大的那个音之后再剪一刀，
    /// 新发的号会和刚删掉的那个撞上。这是可以接受的：那时候那个号已经没有合法持有者
    /// （拿着它的旧曲子是撤销栈里的历史，不是现在这一份），而身份的作用范围本来就只是一份
    /// <see cref="Song"/> —— 一份曲子里的号不重复，就够所有用得着身份的地方用了。
    /// </summary>
    internal static NoteId FirstFree(IReadOnlyList<Note> notes)
    {
        int max = 0;
        foreach (var note in notes)
            if (note.Id.Value > max) max = note.Id.Value;

        return new NoteId(max + 1);
    }

    /// <summary>
    /// 把一轨音符的身份**盘一遍**：合规（互不相同、且都不是 0 号）就原样还回去，不合规就整轨重发一遍。
    ///
    /// 谁需要这一下：读工程文件之后。文件里的身份是**盘上的数据**，可能是老版本存的（那时还没有这个字段，
    /// 读出来全是 0 号），也可能是人手动改过的（两个音抄成同一个号）。这两种情况都不能往下传：
    /// 「身份在轨内互不相同」是这份数据唯一要保证的事，破了它，按身份认音就会认到两个音上，
    /// 而且不会报错 —— 正是这个类型要避免的那种坏。
    ///
    /// 为什么不合规就**整轨**重发，而不是挑出重复的那几个补号：不合规的文件本来就是坏文件，
    /// 身份在它里面已经不可信了，挑着补只会留下一半可信一半不可信的一轨。整轨重发的规则一句话说得完，
    /// 而且发出的号与「重新导入同一个 MIDI」是同一个函数给的，两边的身份不会各说各话。
    /// </summary>
    internal static Note[] Normalized(IReadOnlyList<Note> notes)
    {
        var seen = new HashSet<int>();
        foreach (var note in notes)
        {
            int id = note.Id.Value;
            if (id == 0 || !seen.Add(id)) return AssignInOrder(notes);
        }

        return notes as Note[] ?? notes.ToArray();
    }
}
