namespace MidiPerformer.Core.Model;

/// <summary>
/// 指向某一份 <see cref="Song"/> 里某个音符的坐标：第几条轨 + **那个音的身份**
/// （<see cref="Note.Id"/>，由读取时发下来，见 <see cref="NoteIdentity"/>）。
///
/// <b>它按身份寻址，不按下标。</b>这正是「选中了哪一个音」这句话能跨过一次编辑的原因：
/// <see cref="Track.Notes"/> 承诺按起始 tick 升序，于是任何一次改动都可能把音符挪到邻居后面、
/// 让整条数组重排 —— 下标一次重排就作废，而且是**一声不吭地**作废（它不会报错，只是指向了另一个音）。
/// 身份不受重排影响：音挪到数组别处去了，指着它的那个号还是指着它。
///
/// <b>从前这里是 (轨, 下标)</b>，界面因此必须存一份**按值**的选中集镜像：记下选中音长什么样
/// （轨 + 音高 + 起点 + 时值 + 力度），命令跑完拿这份内容去新的 <see cref="Track.Notes"/> 里
/// **重新找**它在哪，再把下标装回去。那套东西（连同「按内容找回音符」）的唯一存在理由就是
/// 下标会作废，代价是两个一模一样的音对不上号 —— 真实语料里同刻同音高同力度的两个音是常事
/// （两条声部撞在一起、一个音被复制过），那种情况下它**悄悄地**选中了另一个音。
/// 换成按身份寻址之后编辑不必再做任何事，那套镜像整个删掉了（31 号工单）。
///
/// <b>身份只在一条轨内唯一</b>（见 <see cref="NoteId"/>），所以坐标仍然带着轨那一半：
/// 光一个号说不出是哪条轨上的音。
///
/// 代价说清楚两件：
/// <list type="number">
/// <item>轨那一半仍然是 <b>下标</b>，于是删掉一整条轨之后 <see cref="Song.Tracks"/> 的下标整体前移，
/// 存下来的坐标会指到别的轨上 —— 界面在删轨那一路必须**明确清空选中集**，不能留着旧坐标
/// （和身份没关系，是轨这一半的问题）。</item>
/// <item><see cref="NoteId.None"/>（0 号）不是「没有这个音」，而是「这个音没发过号」：
/// 手工拼出来的音符才是 0 号（见 <see cref="NoteId.None"/>）。两条正经的读取路径
/// （MIDI 导入、读工程文件）都会发号，所以界面手里不会出现 0 号音。</item>
/// </list>
/// </summary>
/// <param name="Track"><see cref="Song.Tracks"/> 里的下标。</param>
/// <param name="Id">该音的身份（<see cref="Note.Id"/>）。</param>
public readonly record struct NoteRef(int Track, NoteId Id);
